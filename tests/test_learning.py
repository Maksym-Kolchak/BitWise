from database import db
from database.models import Enrollment, QuizAttempt, Course, Membership, Company, User


def test_learning_completion_while_in_company_workspace(data, login):
    client = login(data["editor"])
    course = data["published"]
    client.post("/workspaces/select", data={"company_id": 10})
    assert client.post(f"/course/{course.id}/start").status_code == 302
    lesson = course.lessons[0]
    quiz = lesson.quiz
    assert client.get(f"/course/{course.id}/lesson/1").status_code == 200
    answers = {
        f"q_{question.id}": next(a.id for a in question.answers if a.is_correct)
        for question in quiz.questions
    }
    assert (
        client.post(f"/course/{course.id}/lesson/1/quiz", data=answers).status_code
        == 200
    )
    enrollment = Enrollment.query.filter_by(
        user_id=data["editor"].id, course_id=course.id
    ).one()
    assert enrollment.status == "completed"
    assert (
        QuizAttempt.query.filter_by(
            user_id=data["editor"].id, quiz_id=quiz.id, passed=True
        ).count()
        == 1
    )
    # Switching workspaces never changes the learner identity.
    client.post("/workspaces/select", data={"company_id": 20})
    client.post("/workspaces/select", data={"company_id": ""})
    assert b"Public course" in client.get("/account").data


def test_new_signup_is_human_even_if_old_company_field_is_posted(app, monkeypatch):
    sent = []
    monkeypatch.setattr(
        "backend.routes.site_auth.send_email", lambda *args: sent.append(args) or True
    )
    client = app.test_client()
    response = client.post(
        "/signup",
        data={
            "type": "company",
            "email": "new@example.invalid",
            "first_name": "New",
            "last_name": "Author",
            "next": "/workspaces",
        },
    )
    assert response.status_code == 302 and sent
    assert User.query.filter_by(email="new@example.invalid").first() is None
    # Follow the confirmation link generated by the real signup route.
    link = next(line for line in sent[0][2].splitlines() if "/signup/confirm/" in line)
    from urllib.parse import urlsplit

    response = client.get(urlsplit(link).path)
    assert response.status_code == 302 and response.location == "/workspaces"
    user = User.query.filter_by(email="new@example.invalid").one()
    assert user.person.first_name == "New"
    assert Company.query.filter_by(owner_id=user.id).count() == 0


def test_same_email_rejects_duplicate_signup(app, data):
    response = app.test_client().post(
        "/signup",
        data={"email": data["owner"].email, "first_name": "Name", "last_name": "Last"},
    )
    assert response.status_code == 302
    assert User.query.filter_by(email=data["owner"].email).count() == 1


def test_legacy_company_owner_can_complete_personal_profile(app, data, login):
    user = data["owner"]
    db.session.delete(user.person)
    user.person = None
    db.session.commit()
    client = login(user)
    assert client.get("/account").status_code == 200
    assert (
        client.post(
            "/account/edit", data={"first_name": "Real", "last_name": "Name"}
        ).status_code
        == 302
    )
    db.session.refresh(user)
    assert user.person.first_name == "Real"
    assert Membership.query.filter_by(
        user_id=user.id, company_id=10, role="owner"
    ).one()
